func TestSetFlag(t *testing.T) {
	ram := memory.NewRAM()
	cpu := NewCPU(ram)

	cpu.SetFlag(true, Carry)

	if cpu.GetFlag(Carry) != 1 {
		t.Errorf("expected Carry flag = 1")
	}

	cpu.SetFlag(false, Carry)

	if cpu.GetFlag(Carry) != 0 {
		t.Errorf("expected Carry flag = 0")
	}
}

func TestGetFlag(t *testing.T) {
	ram := memory.NewRAM()
	cpu := NewCPU(ram)

	if cpu.GetFlag(Zero) != 0 {
		t.Errorf("expected Zero flag = 0")
	}

	cpu.SetFlag(true, Negative)

	if cpu.GetFlag(Negative) != 1 {
		t.Errorf("expected Negative flag = 1")
	}
}

func TestResetInterrupt(t *testing.T) {
	ram := memory.NewRAM()
	cpu := NewCPU(ram)

	cpu.Mem.Write(0xFFFC, 0x34)
	cpu.Mem.Write(0xFFFD, 0x12)

	cpu.Interrupt(RESET)

	if cpu.pc != 0x1234 {
		t.Errorf("expected PC=0x1234, got %#x", cpu.pc)
	}

	if cpu.sp != 0xFD {
		t.Errorf("expected SP=0xFD")
	}

	if cpu.ps != 0x24 {
		t.Errorf("expected PS=0x24, got %#x", cpu.ps)
	}
}

